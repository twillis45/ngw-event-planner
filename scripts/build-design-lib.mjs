#!/usr/bin/env node
// Library build for the NGW Operational Design System.
//
// src/design/ is consumed internally by the CRA app, which means it had no
// compiled entry — no dist, no `main`/`module`/`exports`. Anything downstream
// that wants the system (a Claude Design sync, another app, a docs site) had to
// read source and infer the API. This emits a real entry so the contract comes
// from built output instead of a guess.
//
//   npm run design:build   ->  dist-design/index.mjs  (+ .cjs)
//
// esbuild rather than vite/tsup: one dependency, no config file, and it is what
// vite runs underneath for this anyway. React stays external — the consumer
// brings its own, and bundling a second copy breaks hooks.
import { build } from 'esbuild';
import { rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outdir = path.join(root, 'dist-design');
const entry = path.join(root, 'src/design/index.js');

await rm(outdir, { recursive: true, force: true });

const shared = {
  entryPoints: [entry],
  bundle: true,
  // React and the JSX runtime come from the host. A design system that bundles
  // its own React gives the consumer two renderers and hooks that throw.
  external: ['react', 'react-dom', 'react/jsx-runtime'],
  jsx: 'automatic',
  loader: { '.js': 'jsx' }, // .js files here contain JSX (CRA convention)
  target: ['es2020'],
  logLevel: 'info',
};

await build({ ...shared, format: 'esm', outfile: path.join(outdir, 'index.mjs') });
await build({ ...shared, format: 'cjs', outfile: path.join(outdir, 'index.cjs') });

// Hand-written types. The source is plain JSX with no TypeScript, so nothing can
// be extracted — and the props ARE the API: a consumer that doesn't know
// priority="escalation" or severity="emergency" exists cannot use the system.
// Enum members are spelled out rather than widened to string on purpose.
await writeFile(path.join(outdir, 'index.d.ts'), `// Generated by scripts/build-design-lib.mjs — hand-authored contracts.
// The source is plain JSX; these are written, not extracted. Keep in sync with
// the primitives' destructured props when they change.
import type { CSSProperties, ReactNode, ElementType, MouseEventHandler } from 'react';

export interface ButtonProps {
  /** Structural primacy. One p1 per surface; escalation wins in escalated context. */
  priority?: 'p1' | 'p2' | 'ambient' | 'escalation';
  size?: 'sm' | 'md' | 'lg' | 'xl';
  full?: boolean;
  disabled?: boolean;
  onClick?: MouseEventHandler<HTMLButtonElement>;
  style?: CSSProperties;
  children?: ReactNode;
}
export declare function Button(props: ButtonProps): JSX.Element;

export interface TextProps {
  variant?: 'display' | 'title' | 'section' | 'body' | 'caption' | 'label' | 'mono';
  /** Rendered element. Pick for semantics; variant carries the look. */
  as?: ElementType;
  color?: string;
  style?: CSSProperties;
  children?: ReactNode;
}
export declare function Text(props: TextProps): JSX.Element;

export interface SurfaceProps {
  role?: 'canvas' | 'card' | 'active' | 'escalation' | 'interrupt';
  /** Overrides DensityContext for this subtree. */
  density?: 'full' | 'compact' | 'crisis';
  /** Key into the space scale (0-12), not a pixel value. */
  pad?: number;
  rad?: 'none' | 'sm' | 'md' | 'lg' | 'xl' | 'full';
  border?: boolean;
  style?: CSSProperties;
  children?: ReactNode;
}
export declare function Surface(props: SurfaceProps): JSX.Element;

export interface AlertBannerProps {
  severity?: 'nominal' | 'caution' | 'escalated' | 'emergency';
  title?: ReactNode;
  body?: ReactNode;
  /** Trailing action slot — usually a <Button priority="p2">. */
  action?: ReactNode;
  style?: CSSProperties;
}
export declare function AlertBanner(props: AlertBannerProps): JSX.Element;

export interface EscalationBadgeProps {
  status?: 'neutral' | 'nominal' | 'caution' | 'escalated' | 'emergency';
  dot?: boolean;
  style?: CSSProperties;
  children?: ReactNode;
}
export declare function EscalationBadge(props: EscalationBadgeProps): JSX.Element;

export interface BottomSheetProps {
  open: boolean;
  onClose?: () => void;
  title?: ReactNode;
  /** 'auto' fits content; 'peek' is the partial rise; a number is px. */
  height?: 'auto' | 'peek' | number;
  style?: CSSProperties;
  children?: ReactNode;
}
export declare function BottomSheet(props: BottomSheetProps): JSX.Element;

// ── Providers — required, not optional ────────────────────────────────────
// Button and AlertBanner read EscalationContext; Surface reads DensityContext.
export interface EscalationProviderProps {
  initialLevel?: 'nominal' | 'caution' | 'escalated' | 'emergency';
  children?: ReactNode;
}
export declare function EscalationProvider(props: EscalationProviderProps): JSX.Element;
export declare function useEscalation(): { level: string; [k: string]: unknown };
export declare const ESCALATION_LEVELS: readonly ['nominal', 'caution', 'escalated', 'emergency'];

export interface DensityProviderProps {
  override?: 'full' | 'compact' | 'crisis' | null;
  children?: ReactNode;
}
export declare function DensityProvider(props: DensityProviderProps): JSX.Element;
export declare function useDensity(): { density: string };
export declare const DENSITIES: readonly ['full', 'compact', 'crisis'];

// ── Tokens ────────────────────────────────────────────────────────────────
export declare const color: Record<string, any>;
export declare const space: Record<number, number>;
export declare const radius: Record<string, number>;
export declare const type: Record<string, any>;
export declare const motion: { ease: Record<string, string>; duration: Record<string, number> };
export declare const elevation: Record<string, string>;
export declare const legacyBridge: Record<string, string>;
export declare const tokens: Record<string, any>;
export declare const choreography: Record<string, { ms: number; ease: string }>;
export declare function transitionFor(intent: string, props?: string[]): string;
export declare function surfaceFor(role: string, density?: string): Record<string, any>;
export declare function visibleCountFor(density: string, base: number): number;
`);

console.log('\n✓ design library built -> dist-design/ (index.mjs, index.cjs, index.d.ts)');
