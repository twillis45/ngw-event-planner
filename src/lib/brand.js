// ─── WHAT THIS PRODUCT IS CALLED, IN ONE PLACE ───────────────────────────────
//
// The product name was hand-typed 148 times across 22 runtime files. Renaming it
// therefore meant editing 22 files and hoping, which is the same duplication
// class as the diet vocabulary, the guest-count chips and the `anyDiet` predicate
// — a fact with no owner, restated by every consumer.
//
// WHY IT IS BEING RENAMED (host decision 2026-09-23). "Event Boss" is a LIVE
// PRODUCT IN THIS EXACT CATEGORY, not merely a similar company name: Event Boss
// is listed on GetApp UK for 2026 as event-management software for wedding
// planners, venues, decorators and caterers. Shipping under it would put a
// one-person US product under a name a UK competitor already trades on, in the
// same buyer's search results.
//
// "No Guesswork Events" is a sibling of No Guesswork Systems LLC, which the
// owner already operates — so it needs no new entity, and its distinctiveness
// rests on a mark he already uses rather than on a phrase competitors put in
// their marketing copy. It also happens to name what the product actually does:
// this codebase's whole discipline is refusing to state what it has not
// measured, and the name says so.
//
// NOT A LEGAL CLEARANCE. No trademark search was run and none is implied. A
// USPTO search and an attorney's opinion are still required before relying on
// this commercially — nothing here substitutes for that.
//
// TWO FORMS, ON PURPOSE. `full` is the identity: wordmark, splash, welcome, the
// name of a paid pass. `short` is for running prose, where the three-word form
// reads as a corporate insert — "What No Guesswork remembers" is a sentence, and
// "What No Guesswork Events remembers" is a press release. Surfaces pick the one
// that fits; neither is ever re-typed.
export const BRAND = Object.freeze({
  full: 'No Guesswork Events',
  short: 'No Guesswork',
  caps: 'NO GUESSWORK EVENTS',
  company: 'No Guesswork Systems LLC',
});

export default BRAND;
